/**
 * How the suite runs the transcoder (`E2E_TRANSCODER`):
 * - `host`: `node dist/main.js` in apps/transcoder, like the api and the worker (CI). Needs
 *   ffmpeg/ffprobe >= 6 (`TRANSCODER_FFMPEG_PATH` / `TRANSCODER_FFPROBE_PATH`, default PATH).
 * - `compose`: the `transcoder` service of the dev compose file (the production image with its
 *   pinned ffmpeg), for machines without ffmpeg. Its health port is published on 127.0.0.1 by
 *   infra/docker/docker-compose.e2e.yml.
 * - `external`: not started by the suite (one is already running against the same stack).
 *
 * Default: `host` when ffmpeg runs from the host, else `compose`.
 */
export type TranscoderMode = 'host' | 'compose' | 'external';

export const ffmpegPath = serverSetting('TRANSCODER_FFMPEG_PATH') ?? 'ffmpeg';

export function hostHasFfmpeg(): boolean {
  const result = spawnSync(ffmpegPath, ['-hide_banner', '-version'], {
    stdio: 'ignore',
    timeout: 10_000,
  });
  return result.error === undefined && result.status === 0;
}

function resolveTranscoderMode(): TranscoderMode {
  const raw = process.env.E2E_TRANSCODER;
  if (raw === 'host' || raw === 'compose' || raw === 'external') return raw;
  if (raw !== undefined && raw !== '') {
    throw new Error(`E2E_TRANSCODER must be host, compose or external, got ${JSON.stringify(raw)}`);
  }
  return hostHasFfmpeg() ? 'host' : 'compose';
}

export const transcoderMode: TranscoderMode = resolveTranscoderMode();

/** Env overrides for `node dist/main.js` in apps/transcoder (host mode). */
export function transcoderEnv(): Record<string, string> {
  return {
    TRANSCODER_HEALTH_PORT: String(ports.transcoder),
    // Same ceiling as the compose service and CI: a 5 s fixture needs one or two rungs only.
    TRANSCODER_MAX_HEIGHT: process.env.TRANSCODER_MAX_HEIGHT ?? '720',
    LOG_LEVEL: process.env.E2E_SERVER_LOG_LEVEL ?? 'info',
  };
}

/** `docker compose` with the dev stack file plus the e2e overlay (transcoder health port). */
export function composeArgs(): string[] {
  const envFile = resolve(REPO_ROOT, '.env');
  return [
    'compose',
    ...(existsSync(envFile) ? ['--env-file', envFile] : []),
    '-f',
    resolve(REPO_ROOT, 'infra/docker/docker-compose.dev.yml'),
    '-f',
    resolve(REPO_ROOT, 'infra/docker/docker-compose.e2e.yml'),
    '--profile',
    'transcoder',
  ];
}

/** The image the compose `transcoder` service runs; also used to run ffmpeg for the fixtures. */
export const TRANSCODER_IMAGE = 'udemy-transcoder:dev';

/**
 * Full server env of one Next BFF for `next start`. The client secret comes from
 * `E2E_<APP>_CLIENT_SECRET` (CI: random per job, its SHA-256 in CLIENT_<APP>_SECRET_HASH), else the
 * app's `.env.local` (else `.env.example`, whose dev placeholder matches the root .env hash).
 */
export function webEnv(app: AppName): Record<string, string> {
  const appDir = resolve(REPO_ROOT, `apps/web-${app}`);
  const local = readEnvFile(resolve(appDir, '.env.local'), resolve(appDir, '.env.example'));
  const secretOverride = process.env[`E2E_${app.toUpperCase()}_CLIENT_SECRET`];
  const env: Record<string, string> = {
    NODE_ENV: 'production',
    PORT: String(ports[app]),
    API_INTERNAL_URL: urls.api,
    API_CLIENT_ID: local.API_CLIENT_ID ?? `${app}-bff`,
    API_CLIENT_SECRET: secretOverride || local.API_CLIENT_SECRET || '',
    APP_ORIGIN: urls[app],
    JWT_ISSUER: urls.api,
    JWT_AUDIENCE: rootEnv.JWT_AUDIENCE ?? 'udemy-api',
    JWKS_URL: `${urls.api}/.well-known/jwks.json`,
    COOKIE_SECURE: 'true',
    // CSP connect-src / img-src / media-src: must be the origin the api signs URLs for.
    MEDIA_PUBLIC_ORIGIN: mediaPublicOrigin,
  };
  // Instructor: links to /become-instructor. Admin: links live courses to their public page.
  if (app === 'instructor' || app === 'admin') env.STUDENT_APP_ORIGIN = urls.student;
  return env;
}

/** Cookie names of each BFF (`__Host-udemy-{app}-{rt|at}` with COOKIE_SECURE=true). */
export function cookieName(app: AppName, kind: 'rt' | 'at'): string {
  return `__Host-udemy-${app}-${kind}`;
}
